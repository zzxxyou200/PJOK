-- PostgreSQL schema and demo data converted from the shared MySQL export.
-- Safe to run on an empty Neon database. Existing conflicting rows are left unchanged.
BEGIN;

CREATE TABLE IF NOT EXISTS app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    username VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS cart (
    id VARCHAR(255) PRIMARY KEY,
    product_id VARCHAR(255),
    price DOUBLE PRECISION,
    user_id VARCHAR(255),
    create_dt DATE,
    update_dt DATE,
    create_by VARCHAR(255),
    update_by VARCHAR(255),
    amount INTEGER,
    status VARCHAR(255),
    unit_type VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    description VARCHAR(500),
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS product_items (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condition_status VARCHAR(255),
    created_at TIMESTAMP(6),
    images TEXT,
    item_status VARCHAR(255),
    note VARCHAR(500),
    product_name VARCHAR(255),
    serial_number VARCHAR(255),
    updated_at TIMESTAMP(6),
    warranty_end_date DATE,
    warranty_start_date DATE,
    stock_quantity INTEGER NOT NULL DEFAULT 1,
    unit_type VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS product_item_categories (
    product_id BIGINT NOT NULL REFERENCES product_items(product_id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
    PRIMARY KEY (product_id, category_id)
);
CREATE INDEX IF NOT EXISTS fk_pic_category ON product_item_categories(category_id);

CREATE TABLE IF NOT EXISTS product_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    effective_from TIMESTAMP(6),
    effective_to TIMESTAMP(6),
    note VARCHAR(500),
    organization_id BIGINT,
    price NUMERIC(38, 2),
    product_id BIGINT,
    status VARCHAR(10),
    updated_at TIMESTAMP(6),
    box_price NUMERIC(38, 2)
);

CREATE TABLE IF NOT EXISTS product_sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES product_items(product_id) ON DELETE CASCADE,
    organization_id BIGINT,
    quantity INTEGER NOT NULL,
    price NUMERIC(38, 2),
    sale_date TIMESTAMP(6)
);
CREATE INDEX IF NOT EXISTS fk_ps_product ON product_sales(product_id);

CREATE TABLE IF NOT EXISTS purchese_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount INTEGER NOT NULL,
    checkout_id VARCHAR(255) NOT NULL,
    price NUMERIC(38, 2),
    product_id BIGINT NOT NULL,
    product_name VARCHAR(255),
    purchase_date TIMESTAMP(6),
    serial_number VARCHAR(255),
    total NUMERIC(38, 2),
    unit_type VARCHAR(255),
    user_id VARCHAR(255) NOT NULL,
    delivery_status VARCHAR(32) DEFAULT 'PENDING',
    payment_status VARCHAR(32) DEFAULT 'PENDING'
);

